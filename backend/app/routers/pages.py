@router.get("/Login", response_class=HTMLResponse)
@router.get("/Login.html", response_class=HTMLResponse)
@router.get("/signin", response_class=HTMLResponse)
def login_page(request: Request, user: dict = Depends(get_current_user_optional)):
    if user:
        return RedirectResponse(url="/app/dashboard")
    response = templates.TemplateResponse(request=request, name="pages/login.html", context={
        "user": None,
        "app_name": settings.APP_NAME
    })
    # If client has a stale/invalid session cookie, clear it cleanly
    if settings.COOKIE_NAME in request.cookies:
        response.delete_cookie(key=settings.COOKIE_NAME)
    return response

