doc_repo = DocumentRepository()

def resolve_active_document(document_id: str = None) -> tuple:
    """Resolve requested document, or dynamically pick the latest user-uploaded document."""
    all_docs = doc_repo.list_all(limit=50)
    # Filter out automated test dummy files generated by pytest if any
    clean_docs = [
        d for d in all_docs
        if not (
            "test" in str(d.get("title", "")).lower()
            and "historical survey deed 1905" in str(d.get("title", "")).lower()
        )
    ]
    if not clean_docs:
        clean_docs = all_docs

    if document_id:
        doc = doc_repo.find_by_id(document_id)
        if doc:
            return doc, doc.get("document_id"), clean_docs
    if clean_docs:
        # Prioritize real user uploads (e.g. DOC-1918-HLT, test5, test3) over sample seed records
        seed_ids = {"DOC-1912-KDL", "DOC-1888-BNG", "DOC-1934-BOM"}
        user_uploads = [d for d in clean_docs if d.get("document_id") not in seed_ids]
        chosen = user_uploads[0] if user_uploads else clean_docs[0]
        return chosen, chosen.get("document_id"), clean_docs
    return None, None, []

def auth_guard(request: Request, user: dict):
    """Ensure user is logged in for app routes."""
    if not user:
        path = request.url.path
        if path.startswith("/login"):
            return None
        return RedirectResponse(url=f"/login?redirect={path}")
    return None

